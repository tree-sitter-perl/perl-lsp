/// Retained read connections: opened through the caller's opener, reused
/// across calls, reopened when the DB file was unlinked/recreated
/// underneath one (inode change — `--clear-cache`, a row-format rebuild).
///
/// The ONE speller of retain-with-recheck: `ModuleIndex::with_rows_conn`,
/// the bag-LRU loader and the conclusion cache's loader all ride it. A
/// per-call open costs milliseconds (file open, WAL handshake, the
/// CANTOPEN retry ladder) against the microsecond query it serves —
/// measured at 5.1 ms/call over 70k conclusion-map loads, 360 s of
/// accumulated open cost in one cold `--check`, 13x the next-largest term
/// in the run.
///
/// A CHECKOUT POOL, not one guarded connection: `with` holds the lock only
/// to take a connection out and to put it back, never across `f`. The blob
/// loader decodes inside `f` (10 µs–3 ms per miss), and one mutex around
/// it serialized every rehydrate in the process — a 20-worker `--heatmap`
/// gather measured 188% CPU with that lock in place. Sequential callers
/// still see exactly one connection; concurrent callers grow the pool to
/// their peak overlap and reuse it from then on.
pub struct RetainedReader {
    pool: std::sync::Mutex<Vec<(Connection, u64)>>,
    /// How stale a checked-out connection's inode verdict may be. The
    /// recheck is a `stat` of the DB path, and a `--check` sweep checks out
    /// millions of times: per checkout it was 1.2M syscalls on one corpus.
    /// The unlinks it detects come from ANOTHER process (`--clear-cache`), so
    /// a bounded lag costs one late reopen, never a wrong answer in this one.
    recheck_every: std::time::Duration,
    /// Process-relative millis of the last inode recheck (0 = never).
    last_recheck_ms: std::sync::atomic::AtomicU64,
}

/// See `RetainedReader::recheck_every`.
const INODE_RECHECK_EVERY: std::time::Duration = std::time::Duration::from_secs(1);

fn process_millis() -> u64 {
    static START: std::sync::OnceLock<std::time::Instant> = std::sync::OnceLock::new();
    // +1 so a recheck at the very start never reads as "never".
    START.get_or_init(std::time::Instant::now).elapsed().as_millis() as u64 + 1
}

impl Default for RetainedReader {
    fn default() -> Self {
        Self::new()
    }
}

impl RetainedReader {
    pub fn new() -> Self {
        Self::with_recheck_every(INODE_RECHECK_EVERY)
    }

    fn with_recheck_every(recheck_every: std::time::Duration) -> Self {
        RetainedReader {
            pool: std::sync::Mutex::new(Vec::new()),
            recheck_every,
            last_recheck_ms: std::sync::atomic::AtomicU64::new(0),
        }
    }

    /// Is a recheck due? Claims the slot, so concurrent checkouts in one
    /// window stat once between them.
    fn recheck_due(&self) -> bool {
        use std::sync::atomic::Ordering;
        let now = process_millis();
        let last = self.last_recheck_ms.load(Ordering::Relaxed);
        if last != 0 && now.saturating_sub(last) < self.recheck_every.as_millis() as u64 {
            return false;
        }
        self.last_recheck_ms
            .compare_exchange(last, now, Ordering::Relaxed, Ordering::Relaxed)
            .is_ok()
    }

    fn db_ino(conn: &Connection) -> u64 {
        #[cfg(unix)]
        {
            use std::os::unix::fs::MetadataExt;
            return conn
                .path()
                .and_then(|p| std::fs::metadata(p).ok())
                .map(|m| m.ino())
                .unwrap_or(0);
        }
        #[cfg(not(unix))]
        {
            let _ = conn;
            0
        }
    }

    /// Drop the held connection — the next `with` reopens. For callers whose
    /// OPENER changed (a new workspace root), which the inode recheck cannot
    /// see: same file may exist at both paths.
    pub fn reset(&self) {
        let mut guard = self.pool.lock().unwrap_or_else(|p| p.into_inner());
        guard.clear();
    }

    /// Run `f` on the retained connection, opening through `opener` when
    /// none is held or the file moved underneath it. `None` when the open
    /// fails — a failure is NOT retained, so a DB created later is picked
    /// up on the next call.
    pub fn with<R>(
        &self,
        opener: impl FnOnce() -> Option<Connection>,
        f: impl FnOnce(&Connection) -> R,
    ) -> Option<R> {
        // Poison-proof: the pool is a pure cache — a panic in an earlier
        // holder must not permanently disable retrieval (a connection
        // checked out by a panicking caller is simply never returned).
        let held = {
            let mut pool = self.pool.lock().unwrap_or_else(|p| p.into_inner());
            if self.recheck_due() {
                // One stat answers for the whole pool: every connection names
                // the same path. A file unlinked/recreated underneath drops
                // each connection opened on the old inode.
                if let Some(current) = pool.last().map(|(c, _)| Self::db_ino(c)) {
                    pool.retain(|(_, ino)| *ino == current);
                }
            }
            pool.pop()
        };
        let (conn, ino) = match held {
            Some(h) => h,
            None => {
                let c = opener()?;
                let ino = Self::db_ino(&c);
                (c, ino)
            }
        };
        let out = f(&conn);
        self.pool.lock().unwrap_or_else(|p| p.into_inner()).push((conn, ino));
        Some(out)
    }
}

#[cfg(test)]
mod retained_reader_tests {
    use super::RetainedReader;

    /// One open serves many calls; a recreated DB file (new inode) forces a
    /// reopen. The two behaviors this struct exists for, and the second is
    /// what keeps `--clear-cache` honest mid-session.
    #[test]
    fn opens_once_and_reopens_on_inode_change() {
        let dir = std::env::temp_dir().join(format!("rr_test_{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let db = dir.join("t.db");
        super::Connection::open(&db).unwrap().execute_batch("CREATE TABLE t(x)").unwrap();

        let rr = RetainedReader::with_recheck_every(std::time::Duration::ZERO);
        let opens = std::cell::Cell::new(0u32);
        let opener = || {
            opens.set(opens.get() + 1);
            super::Connection::open(&db).ok()
        };
        assert!(rr.with(opener, |_| ()).is_some());
        assert!(rr.with(opener, |_| ()).is_some());
        assert_eq!(opens.get(), 1, "the second call rides the retained connection");

        std::fs::remove_file(&db).unwrap();
        super::Connection::open(&db).unwrap().execute_batch("CREATE TABLE t(x)").unwrap();
        assert!(rr.with(opener, |_| ()).is_some());
        assert_eq!(opens.get(), 2, "a recreated file (new inode) must reopen");

        let _ = std::fs::remove_dir_all(&dir);
    }

    /// A failed open is not retained: a DB that appears later is picked up.
    #[test]
    fn a_failed_open_is_retried_next_call() {
        let dir = std::env::temp_dir().join(format!("rr_late_{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let db = dir.join("late.db");

        let rr = RetainedReader::new();
        assert!(rr.with(|| None, |_: &super::Connection| ()).is_none());
        super::Connection::open(&db).unwrap().execute_batch("CREATE TABLE t(x)").unwrap();
        assert!(
            rr.with(|| super::Connection::open(&db).ok(), |_| ()).is_some(),
            "the earlier failure must not be remembered as permanent"
        );
        let _ = std::fs::remove_dir_all(&dir);
    }
}
